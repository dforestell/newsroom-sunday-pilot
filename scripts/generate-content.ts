// Build step: validates content/stories and content/calls and inlines them into a
// TypeScript module so the server bundle never reads content/, app/ or public/ at runtime.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { loadCalls } from "../lib/calls/files.ts";
import { CallFilingError } from "../lib/calls/content.ts";
import { FilingError } from "../lib/stories/content.ts";
import { loadStoriesWithRoutes, publicAssets } from "../lib/stories/files.ts";

const out = resolve("lib/generated/content.ts");
try {
  const { stories, routes } = loadStoriesWithRoutes();
  const calls = loadCalls();
  const routeTable = Object.fromEntries([...routes].map(([path, anchors]) => [path, [...anchors].sort()]));
  const source = `// GENERATED by scripts/generate-content.ts from content/. Do not edit; run npm run gen:content.
import type { Story } from "../stories/content.ts";
import type { Call } from "../calls/content.ts";

export const FILE_STORIES: Story[] = ${JSON.stringify(stories, null, 1)};

export const FILE_CALLS: Call[] = ${JSON.stringify(calls, null, 1)};

/** Known site routes (with heading/entry anchors) for validating links in admin stories. */
export const ROUTES: Record<string, string[]> = ${JSON.stringify(routeTable)};

export const PUBLIC_ASSETS: string[] = ${JSON.stringify(publicAssets(process.cwd()))};
`;
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, source);
  console.log(`Generated lib/generated/content.ts: ${stories.length} stories, ${calls.length} calls.`);
} catch (error) {
  if (!(error instanceof FilingError) && !(error instanceof CallFilingError)) throw error;
  console.error(error.message);
  process.exitCode = 1;
}
